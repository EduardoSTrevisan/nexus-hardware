-- As instruções não apagam outros bancos e não criam novamente as tabelas existentes.
BEGIN;
CREATE TABLE IF NOT EXISTS produtos (
    id INTEGER PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    tipo VARCHAR(80) NOT NULL,
    preco_centavos INTEGER NOT NULL CHECK (preco_centavos >= 0),
    estoque INTEGER NOT NULL CHECK (estoque >= 0),
    imagem VARCHAR(255) NOT NULL,
    destaque BOOLEAN NOT NULL DEFAULT FALSE,
    selo VARCHAR(80) NOT NULL DEFAULT '',
    descricao TEXT NOT NULL,
    especificacoes JSONB NOT NULL DEFAULT '[]'::jsonb
);
CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nome VARCHAR(120) NOT NULL,
    cliente_email VARCHAR(160) NOT NULL,
    cep VARCHAR(9) NOT NULL DEFAULT '',
    frete_centavos INTEGER NOT NULL DEFAULT 0 CHECK (frete_centavos >= 0),
    total_centavos BIGINT NOT NULL CHECK (total_centavos >= 0),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pedido_itens (
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    produto_id INTEGER NOT NULL REFERENCES produtos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_centavos INTEGER NOT NULL CHECK (preco_centavos >= 0),
    PRIMARY KEY (pedido_id, produto_id)
);
COMMIT;
